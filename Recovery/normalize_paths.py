#!/usr/bin/env python3
"""Make exported Unity asset paths safe on case-insensitive Windows filesystems.

Preserve paired .meta files; all serialized asset references use their GUIDs.
Directory metadata is not generated by the exporter. Refuse to merge folders
with different directory GUIDs instead of discarding either.
"""
import argparse
import json
from pathlib import Path
import re


def normalize(root):
    changes = []

    def move(source, target):
        if not source.exists():
            return
        if source == target:
            return
        if source.is_dir() and target.exists():
            if source.with_name(source.name + '.meta').exists():
                raise RuntimeError(f'Folder GUID merge needs review: {source}')
            for child in sorted(source.iterdir()):
                move(child, target / child.name)
            source.rmdir()
        else:
            if target.exists():
                if source.name.endswith('.meta'):
                    raise RuntimeError(f'Metadata collision: {source}')
                meta = Path(str(source) + '.meta')
                match = re.search(r'^guid: (\w+)', meta.read_text(), re.M) if meta.exists() else None
                suffix = match[1][:12] if match else 'recovered'
                target = target.with_name(target.stem + '_' + suffix + target.suffix)
                if target.exists():
                    raise RuntimeError(f'Destination exists: {target}')
            old = str(source.relative_to(root))
            paired = Path(str(source) + '.meta')
            source.rename(target)
            changes.append({'from': old, 'to': str(target.relative_to(root))})
            if paired.exists() and not source.name.endswith('.meta'):
                paired.rename(Path(str(target) + '.meta'))

    def visit(folder):
        canonical = {}
        for child in sorted(folder.iterdir(), key=lambda p: (p.name.casefold(), p.name)):
            if not child.exists() or child.name.endswith('.meta'):
                continue
            safe = re.sub(r'[<>:"/\\|?*]', '_', child.name).rstrip(' .')
            if safe.split('.')[0].upper() in {'CON', 'PRN', 'AUX', 'NUL'} | {f'{s}{n}' for s in ('COM', 'LPT') for n in range(1, 10)}:
                safe = '_' + safe
            key = safe.casefold()
            if key in canonical:
                target = canonical[key]
                move(child, target)
            else:
                target = child.with_name(safe)
                move(child, target)
                canonical[key] = target
        for child in sorted(folder.iterdir()):
            if child.is_dir():
                visit(child)

    visit(root)
    return changes


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('assets', type=Path)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    changes = normalize(args.assets.resolve())
    args.report.write_text(json.dumps(changes, indent=2) + '\n')
    print(f'{len(changes)} path changes; asset GUIDs preserved')
